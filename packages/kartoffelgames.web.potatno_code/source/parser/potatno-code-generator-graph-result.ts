import { PotatnoDocumentFunction } from "../document/potatno-document-function.ts";
import { PotatnoDocumentNode } from "../document/potatno-document-node.ts";
import { PotatnoProject } from "../project/potatno-project.ts";
import { PotatnoCodeGeneratorFunctionResult } from "./potatno-code-generator-function-result.ts";

/**
 * Code generation result for the generation of a single function, or its subgraph.
 */
export class PotatnoCodeGeneratorGraphResult<TProject extends PotatnoProject> {
    private readonly mBodyCode: string;
    private readonly mEntryNode: PotatnoDocumentNode<TProject>;
    private readonly mEntryPorts: ReadonlyArray<PotatnoCodeGeneratorGraphResultPort>;
    private readonly mExitNode: PotatnoDocumentNode<TProject>;
    private readonly mExitPorts: ReadonlyArray<PotatnoCodeGeneratorGraphResultPort>;
    private readonly mFunction: PotatnoDocumentFunction<TProject>;
    private readonly mFunctionName: string;
    private readonly mDependencies: Array<PotatnoCodeGeneratorFunctionResult<TProject>>;

    /**
     * The name of the function, as defined in the document function.
     */
    public get functionName(): string {
        return this.mFunctionName;
    }

    /**
     * The document function this graph result represents.
     */
    public get function(): PotatnoDocumentFunction<TProject> {
        return this.mFunction;
    }

    /**
     * The dependent function code generations required by this graph.
     */
    public get dependencies(): ReadonlyArray<PotatnoCodeGeneratorFunctionResult<TProject>> {
        return this.mDependencies;
    }

    /**
     * The imports required by the function, as defined in the document function.
     */
    public get imports(): ReadonlyArray<string> {
        return this.mFunction.imports;
    }

    /**
     * The graph code of the function, as generated by the code generator.
     */
    public get graphCode(): string {
        return this.mBodyCode;
    }

    /**
     * The entry node of the subgraph.
     */
    public get entryNode(): PotatnoDocumentNode<TProject> {
        return this.mEntryNode;
    }

    /**
     * Value output port valueIds of the entry node, in port-definition order.
     * Use these as the function parameter list when wrapping the graph in a callable.
     */
    public get entryPorts(): ReadonlyArray<PotatnoCodeGeneratorGraphResultPort> {
        return this.mEntryPorts;
    }

    /**
     * The exit node of the subgraph.
     */
    public get exitNode(): PotatnoDocumentNode<TProject> {
        return this.mExitNode;
    }

    /**
     * Value input port valueIds of the exit node, in port-definition order.
     * Each valueId is the connected source output's valueId, or the port's direct value when unconnected.
     * Use these as the return values when wrapping the graph in a callable.
     */
    public get exitPorts(): ReadonlyArray<PotatnoCodeGeneratorGraphResultPort> {
        return this.mExitPorts;
    }

    /**
     * Create a new function context instance.
     *
     * @param pParameters - The parameters for constructing the function context.
     */
    public constructor(pParameters: PotatnoCodeGeneratorGraphResultConstructorParameter<TProject>) {
        this.mFunction = pParameters.function;
        this.mFunctionName = pParameters.functionName;
        this.mEntryNode = pParameters.entryNode;
        this.mExitNode = pParameters.exitNode;
        this.mBodyCode = pParameters.bodyCode;
        this.mEntryPorts = [...pParameters.entryPorts];
        this.mExitPorts = [...pParameters.exitPorts];

        // Initialize dependencies as an empty array. Dependencies can be added later using the addDependency method.
        this.mDependencies = new Array<PotatnoCodeGeneratorFunctionResult<TProject>>();
    }

    public addDependency(pDependency: PotatnoCodeGeneratorFunctionResult<TProject>): void {
        this.mDependencies.push(pDependency);
    }
}

export type PotatnoCodeGeneratorGraphResultPort = {
    /**
     * The port definition id.
     */
    definitionId: string;

    /**
     * The generated valueId associated with the port for the current generation pass.
     */
    valueId: string;
};

export type PotatnoCodeGeneratorGraphResultConstructorParameter<TProject extends PotatnoProject> = {
    /**
     * Display name of the function of the subgraph.
     */
    functionName: string;

    /**
     * The document function of the subgraph.
     */
    function: PotatnoDocumentFunction<TProject>;

    /**
     * The entry node of the subgraph.
     */
    entryNode: PotatnoDocumentNode<TProject>;

    /**
     * Value output port valueIds of the entry node.
     */
    entryPorts: ReadonlyArray<PotatnoCodeGeneratorGraphResultPort>;

    /**
     * The exit node of the subgraph.
     */
    exitNode: PotatnoDocumentNode<TProject>;

    /**
     * Value input port valueIds of the exit node.
     */
    exitPorts: ReadonlyArray<PotatnoCodeGeneratorGraphResultPort>;

    /**
     * The body code of the function, as generated by the code generator.
     */
    bodyCode: string;
};
